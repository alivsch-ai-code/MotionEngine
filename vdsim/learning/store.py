"""On-disk registry of neural models: <dir>/<id>.json (metadata) + <id>.bin (weights / ONNX graph).

Directory: MOTIONENGINE_MODEL_DIR, default ~/.motionengine/models. Ids are generated by the store
([a-z0-9]{12}); client input never becomes a path.
"""

from __future__ import annotations

import json
import os
import re
import threading
import time
import uuid
from pathlib import Path

from .backends import load_backend
from .vehicle import register_neural_model

ID_RE = re.compile(r"^[a-f0-9]{12}$")


class ModelStore:
    def __init__(self, directory=None):
        directory = directory or os.environ.get("MOTIONENGINE_MODEL_DIR") or Path.home() / ".motionengine" / "models"
        self.dir = Path(directory)
        self.dir.mkdir(parents=True, exist_ok=True)
        self._lock = threading.Lock()
        self._backends = {}

    @staticmethod
    def new_id():
        return uuid.uuid4().hex[:12]

    def _paths(self, model_id):
        if not ID_RE.match(str(model_id)):
            raise KeyError(model_id)
        return self.dir / f"{model_id}.json", self.dir / f"{model_id}.bin"

    def save(self, meta, blob=None, model_id=None):
        model_id = model_id or self.new_id()
        jp, bp = self._paths(model_id)
        meta = {**meta, "id": model_id, "created": meta.get("created", time.time()),
                "vehicle_model": f"neural_{model_id}"}
        with self._lock:
            if blob is not None:
                bp.write_bytes(blob)
            jp.write_text(json.dumps(meta, indent=1), encoding="utf-8")
            self._backends.pop(model_id, None)
        return meta

    def list(self):
        out = []
        for jp in sorted(self.dir.glob("*.json")):
            try:
                out.append(json.loads(jp.read_text(encoding="utf-8")))
            except (OSError, ValueError):
                continue
        return sorted(out, key=lambda m: -m.get("created", 0))

    def get(self, model_id):
        jp, _ = self._paths(model_id)
        if not jp.exists():
            raise KeyError(model_id)
        return json.loads(jp.read_text(encoding="utf-8"))

    def delete(self, model_id):
        jp, bp = self._paths(model_id)
        if not jp.exists():
            raise KeyError(model_id)
        with self._lock:
            jp.unlink(missing_ok=True)
            bp.unlink(missing_ok=True)
            self._backends.pop(model_id, None)

    def backend(self, model_id):
        with self._lock:
            if model_id not in self._backends:
                meta = self.get(model_id)
                _, bp = self._paths(model_id)
                blob = bp.read_bytes() if bp.exists() else None
                self._backends[model_id] = load_backend(meta, blob)
            return self._backends[model_id]

    def activate(self, model_id):
        # register as vehicle model neural_<id>; returns the registry name
        return register_neural_model(model_id, self.backend(model_id), self.get(model_id))
