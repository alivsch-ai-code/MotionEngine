class CppGenerator(NativeGenerator):
    target = "cpp"
    LANGUAGE_NAME = "C++"
    KEYWORDS = CPP_KEYWORDS
    COMMENT = "//"
    NAMESPACE = "matlab_gen"

    # ------------------------------------------------------------------ syntax hooks
    def constants(self):
        return {"pi": "mlab::pi", "Inf": "mlab::inf", "inf": "mlab::inf", "NaN": "mlab::nan", "nan": "mlab::nan",
                "eps": "mlab::eps", "true": "true", "false": "false"}

    def var_ref(self, name, lhs=False):
        return self.name(name)

    def persistent_read(self, n):
        return f"{self.STATE_ARG}.{n}.value()"

    def persistent_write(self, n, code):
        return f"{self.STATE_ARG}.{n} = {code};"

    def persistent_isempty(self, n):
        return f"!{self.STATE_ARG}.{n}.has_value()"

    def bool_to_num(self, code):
        return f"static_cast<double>({code})"

    def mat_truth(self, arg):
        return f"mlab::truth({arg})"

    def mat_arg(self, e):
        k = self.kind(e)
        if k == "mat":
            return self.code(e)
        return self.num(e, P_OR)

    def mat_value(self, e):
        return self.code(e)

    def mat_empty(self):
        return "mlab::Mat()"

    def mat_from_rows(self, r, c, vals):
        return f"mlab::Mat::from_rows({r}, {c}, {{{vals}}})"

    def mat_hcat(self, parts):
        return parts[0] if len(parts) == 1 else f"mlab::hcat({{{', '.join(parts)}}})"

    def mat_vcat(self, rows):
        return rows[0] if len(rows) == 1 else f"mlab::vcat({{{', '.join(rows)}}})"

    def mat_get(self, name, idx):
        return f"{self.name(name)}({', '.join(idx)})"

    def mat_set(self, name, idx, v):
        return f"{self.name(name)}({', '.join(idx)}) = {v};"

    def mat_end(self, base, k, n):
        return f"{self.name(base)}.{'numel' if n == 1 else 'nrows' if k == 0 else 'ncols'}()"

    def mat_method(self, e, m):
        return f"{self.p(e, P_POST)}.{m}()" if isinstance(e, N.Ident) else f"mlab::Mat({self.code(e)}).{m}()"

    def mat_ctor(self, name, r, c):
        return f"mlab::{name}({r}, {c})"

    def mat_func_name(self, name):
        return "trunc" if name == "fix" else name

    def scalar_func(self, name, a):
        return f"{_STD1[name]}({self.num(a, P_OR)})"

    def scalar_func2(self, name, a, b):
        return f"{_STD2[name]}({self.num(a, P_OR)}, {self.num(b, P_OR)})"

    def scalar_pred(self, name, a):
        return f"std::{name}({self.num(a, P_OR)})"

    def pow_code(self, l, r):
        return f"std::pow({self.num(l, P_OR)}, {self.num(r, P_OR)})"

    def ctype(self, t):
        if t.is_array:
            return "mlab::Mat"
        if t == BOOL:
            return "bool"
        return "double"

    def declare(self, name, t, code, mutable, value=None):
        if t.kind == "func":
            return f"auto {self.name(name)} = {code};"
        return f"{self.ctype(t)} {self.name(name)} = {code};"

    def default_value(self, t):
        return "mlab::Mat()" if t.is_array else "false" if t == BOOL else "0.0"

    def lambda_expr(self, e):
        saved = dict(self.env)
        for p in e.params:
            self.env[p] = SCALAR
        try:
            body = self.num(e.body, P_OR)
        finally:
            self.env = saved
        return f"[=]({', '.join('double ' + self.name(p) for p in e.params)}) {{ return {body}; }}"

    def call_lambda(self, e):
        return f"{self.name(e.base.name)}({', '.join(self.num(a, P_OR) for a in e.args)})"

    def call_local(self, name, args, node, full=False):
        f = self.local[name]
        ft = self._sig.get(name)
        if len(args) > len(f.params):
            self.unsupported(f"zu viele Argumente für '{name}'", node)
        if len(args) < len(f.params):
            self.unsupported(f"'{name}' mit weniger Argumenten als Parametern (nargin) wird nicht übersetzt", node)
        codes = []
        for a, t in zip(args, ft.inputs if ft else [SCALAR] * len(args)):
            codes.append(self.mat_arg(a) if t.is_array else self.num(a, P_OR))
        if f is self.entry and self.persistent_entry:
            codes.insert(0, self.STATE_ARG)
        call = f"{self.name(name)}({', '.join(codes)})"
        if not f.outputs and not full:
            if isinstance(node, N.Index) or isinstance(node, N.Ident):
                return call, P_POST
        if len(f.outputs) > 1 and not full:
            return f"{call}.{self.name(f.outputs[0])}", P_POST
        return call, P_POST

    def if_head(self, cond, ind, first):
        return f"{ind}if ({cond}) {{" if first else f"{ind}}} else if ({cond}) {{"

    def else_head(self, ind):
        return f"{ind}}} else {{"

    def while_head(self, cond, ind):
        return f"{ind}while ({cond}) {{"

    def for_range_head(self, var, a, s, b, ind, name):
        return f"{ind}for (double {var} : mlab::colon({a}, {s}, {b})) {{"

    def for_vec_head(self, var, vec, ind, name):
        return f"{ind}for (double {var} : {vec}.data) {{"

    def return_stmt(self):
        outs = self.func.outputs
        if not outs:
            return "return;"
        if len(outs) == 1:
            return f"return {self.name(outs[0])};"
        return "return {" + ", ".join(self.name(o) for o in outs) + "};"

    def unpack(self, targets, fields, call, ind, n, pair=False):
        if n == 1 and not pair:
            return [f"{ind}{self.name(targets[0])} = {call};"] if targets[0] else [f"{ind}{call};"]
        lines = [f"{ind}{{", f"{ind}{self.INDENT}const auto res = {call};"]
        for t, fld in zip(targets, fields):
            if t:
                lines.append(f"{ind}{self.INDENT}{self.name(t)} = res.{fld if pair else self.name(fld)};")
        return lines + [f"{ind}}}"]

    def print_literal(self, text):
        return f"std::fputs({self.string_literal(text)}, stdout);"

    def _args(self, vals):
        return "".join(", " + (self.string_literal(v) if k == "str" else v) for k, v in vals)

    def print_format(self, text, vals):
        return f"std::printf({self.string_literal(self.c_format(text))}{self._args(vals)});"

    def raise_error(self, text, vals):
        if not vals:
            return f"throw std::runtime_error({self.string_literal(text.replace('%%', '%'))});"
        return f"throw std::runtime_error(mlab::format({self.string_literal(self.c_format(text))}{self._args(vals)}));"

    def disp_mat(self, arg):
        return f"mlab::disp({arg});"

    # ------------------------------------------------------------------ files
    def param_decl(self, f, p, t):
        if p == "~":
            return "double /*unused*/"
        if t.is_array:
            return f"mlab::Mat {self.name(p)}" if (p in self.mutated or self.counts.get(p, 0)) else \
                f"const mlab::Mat& {self.name(p)}"
        return f"double {self.name(p)}"

    def ret_type(self, f, ft):
        if not f.outputs:
            return "void"
        if len(f.outputs) == 1:
            return self.ctype(ft.outputs[0] if ft.outputs[0].kind != "unknown" else SCALAR)
        return self.result_struct_name(f)

    def generate(self):
        funcs = self.collect()
        self._sig = {f.name: ft for f, ft in funcs}
        self.persistent_entry = any(isinstance(s, N.Persistent) for s in N.body_statements(self.entry.body))
        module = self.entry.name
        defs, protos, structs = {}, {}, {}
        for f, ft in funcs:
            self.setup_function(f, ft)
            for o, t in zip(f.outputs, ft.outputs):
                if t.kind not in ("scalar", "bool", "array", "unknown", "none"):
                    self.diag("error", f"Ausgang '{o}' hat den Typ '{t}', nicht übersetzbar", f)
            params = [self.param_decl(f, p, t) for p, t in zip(f.params, ft.inputs)]
            if f is self.entry and self.persistent_entry:
                params.insert(0, f"{self.state_struct_name()}& {self.STATE_ARG}")
            sig = f"{self.ret_type(f, ft)} {self.name(f.name)}({', '.join(params)})"
            protos[f.name] = sig
            if len(f.outputs) > 1:
                fields = "".join(f"\n    {self.ctype(t if t.kind != 'unknown' else SCALAR)} {self.name(o)};"
                                 for o, t in zip(f.outputs, ft.outputs))
                structs[f.name] = f"// outputs of {f.name}\nstruct {self.result_struct_name(f)} {{{fields}\n}};"
            ind = self.INDENT
            body = []
            for n in self.hoisted:
                try:
                    t = self.vtype(n, f)
                    body.append(f"{ind}{self.ctype(t)} {self.name(n)} = {self.default_value(t)};")
                except Unsupported as u:
                    self.diag("error", u.message, u.node or f)
            body += self.block(f.body, ind)
            if not body or not body[-1].strip().startswith("return"):
                if f.outputs:
                    body.append(f"{ind}{self.return_stmt()}")
            doc = [f"// {l}".rstrip() for l in f.doc.split("\n")] if f.doc else []
            defs[f.name] = doc + [sig + " {"] + body + ["}"]
        entry = self.entry.name
        eqs = []
        for f, _ in funcs:
            eqs += self.equations_of(f)
        head_comment = [f"// Generated by vdsim.matlab (target C++17) from {self.mfile.path or '<source>'}.",
                        "// Do not edit by hand; regenerate with: python -m vdsim.matlab convert <file.m> --to cpp"]
        if eqs:
            head_comment.append(f"// Equation references: {', '.join(dict.fromkeys(eqs))}")
        hpp = [f"// {module}.hpp"] + head_comment + ["//"] + [f"// {l}".rstrip() for l in
                                                               (self.entry.doc or "").split("\n")]
        hpp += [f"#ifndef VDSIM_GEN_{module.upper()}_HPP", f"#define VDSIM_GEN_{module.upper()}_HPP", ""]
        if self.persistent_entry:
            hpp.append("#include <optional>")
        hpp += ['#include "matlab_runtime.hpp"', "", f"namespace {self.NAMESPACE} {{", ""]
        if entry in structs:
            hpp += [structs[entry], ""]
        if self.persistent_entry:
            pvars = sorted({n for s in N.body_statements(self.entry.body) if isinstance(s, N.Persistent)
                            for n in s.names})
            ft0 = self._sig[entry]
            fields = "".join(f"\n    std::optional<{self.ctype(ft0.env.get(n, SCALAR) if ft0.env.get(n, SCALAR).kind != 'none' else SCALAR)}> {n};"
                             for n in pvars)
            hpp += [f"// persistent variables of {entry} (empty until first assignment, like MATLAB [])",
                    f"struct {self.state_struct_name()} {{{fields}\n}};", ""]
        hpp += [f"/// {l}".rstrip() for l in (self.entry.doc or entry).split("\n")[:1]]
        hpp += [protos[entry] + ";", "", f"}}  // namespace {self.NAMESPACE}", "", f"#endif  // VDSIM_GEN_{module.upper()}_HPP"]
        cpp = [f"// {module}.cpp"] + head_comment + ["", f'#include "{module}.hpp"', "", "#include <cmath>",
                                                     "#include <cstdio>", "#include <stdexcept>", "",
                                                     f"namespace {self.NAMESPACE} {{", ""]
        locals_ = [f for f, _ in funcs if f is not self.entry]
        if locals_:
            cpp += ["namespace {", ""]
            for f in locals_:
                if f.name in structs:
                    cpp += [structs[f.name], ""]
            cpp += [protos[f.name] + ";" for f in locals_] + ["", "}  // namespace", ""]
        cpp += defs[entry] + [""]
        if locals_:
            cpp += ["namespace {", ""]
            for f in locals_:
                cpp += defs[f.name] + [""]
            cpp += ["}  // namespace", ""]
        cpp += [f"}}  // namespace {self.NAMESPACE}"]
        files = {f"{module}.hpp": "\n".join(hpp) + "\n", f"{module}.cpp": "\n".join(cpp) + "\n",
                 "matlab_runtime.hpp": RUNTIME_HPP}
        ft = self._sig[entry]
        sig = {"module": module, "namespace": self.NAMESPACE, "function": self.name(entry),
               "inputs": [(p, str(t)) for p, t in zip(self.entry.params, ft.inputs)],
               "outputs": [(o, str(t)) for o, t in zip(self.entry.outputs, ft.outputs)],
               "result_struct": self.result_struct_name(self.entry) if len(self.entry.outputs) > 1 else None,
               "state": self.state_struct_name() if self.persistent_entry else None,
               "output_fields": [self.name(o) for o in self.entry.outputs]}
        return GeneratedCode("cpp", files, self.diags, self.name(entry), sig)


