"""MATLAB -> Rust code generator (f64, std only, one self-contained module file).

Scalars are ``f64`` (math via ``f64::sin(x)`` etc.), matrices use the embedded ``mlab::Mat``
(column-major, 1-based ``get``/``set``). Several outputs are returned as a tuple, persistent
variables of the entry function live in a ``<Name>State`` struct (``Option<f64>``) passed as
``&mut``. Matrix values are cloned on assignment (MATLAB copy semantics).
"""

