class RustGenerator(NativeGenerator):
    target = "rust"
    LANGUAGE_NAME = "Rust"
    KEYWORDS = RUST_KEYWORDS
    COMMENT = "//"

    def constants(self):
        return {"pi": "std::f64::consts::PI", "Inf": "f64::INFINITY", "inf": "f64::INFINITY", "NaN": "f64::NAN",
                "nan": "f64::NAN", "eps": "f64::EPSILON", "true": "true", "false": "false"}

    def var_ref(self, name, lhs=False):
        return self.name(name)

    def persistent_read(self, n):
        return f"{self.STATE_ARG}.{n}.unwrap()" if not self.env.get(n, SCALAR).is_array else \
            f"{self.STATE_ARG}.{n}.clone().unwrap()"

    def persistent_write(self, n, code):
        return f"{self.STATE_ARG}.{n} = Some({code});"

    def persistent_isempty(self, n):
        return f"{self.STATE_ARG}.{n}.is_none()"

    def bool_to_num(self, code):
        return f"mlab::b2f({code})"

    def mat_truth(self, arg):
        return f"mlab::truth({arg})"

    def mat_arg(self, e):
        k = self.kind(e)
        if k == "mat":
            if isinstance(e, N.Ident) and e.name not in self.persistent:
                return f"&{self.name(e.name)}"
            return f"&{self.p(e, P_POST)}"
        return f"&mlab::Mat::scalar({self.num(e, P_OR)})"

    def mat_value(self, e):
        if isinstance(e, N.Ident):
            return f"{self.name(e.name)}.clone()"
        return self.code(e)

    def mat_empty(self):
        return "mlab::Mat::default()"

    def mat_from_rows(self, r, c, vals):
        return f"mlab::Mat::from_rows({r}, {c}, &[{vals}])"

    def mat_hcat(self, parts):
        return f"mlab::hcat(&[{', '.join(parts)}])"

    def mat_vcat(self, rows):
        if len(rows) == 1:
            return rows[0]
        return f"mlab::vcat(&[{', '.join('&' + r for r in rows)}])"

    def matrix(self, e):
        code, prec = super().matrix(e)
        return code, prec

    def mat_get(self, name, idx):
        return f"{self.name(name)}.{'get' if len(idx) == 1 else 'get2'}({', '.join(idx)})"

    def mat_set(self, name, idx, v):
        return f"{self.name(name)}.{'set' if len(idx) == 1 else 'set2'}({', '.join(idx)}, {v});"

    def mat_end(self, base, k, n):
        return f"{self.name(base)}.{'numel' if n == 1 else 'nrows' if k == 0 else 'ncols'}()"

    def mat_method(self, e, m):
        return f"{self.name(e.name)}.{m}()" if isinstance(e, N.Ident) else f"({self.code(e)}).{m}()"

    def mat_ctor(self, name, r, c):
        return f"mlab::{name}({r}, {c})"

    def mat_func_name(self, name):
        return {"fix": "trunc", "sign": "sign_mat"}.get(name, name)

    def scalar_func(self, name, a):
        if name == "sign":
            return f"mlab::sign({self.num(a, P_OR)})"
        return f"f64::{_F64_1[name]}({self.num(a, P_OR)})"

    def scalar_func2(self, name, a, b):
        x, y = self.num(a, P_OR), self.num(b, P_OR)
        return {"atan2": f"f64::atan2({x}, {y})", "hypot": f"f64::hypot({x}, {y})", "mod": f"mlab::modulo({x}, {y})",
                "rem": f"mlab::rem({x}, {y})", "max": f"f64::max({x}, {y})", "min": f"f64::min({x}, {y})",
                "power": f"f64::powf({x}, {y})"}[name]

    def scalar_pred(self, name, a):
        return f"f64::{'is_nan' if name == 'isnan' else 'is_infinite' if name == 'isinf' else 'is_finite'}" \
               f"({self.num(a, P_OR)})"

    def pow_code(self, l, r):
        return f"f64::powf({self.num(l, P_OR)}, {self.num(r, P_OR)})"

    def rtype(self, t):
        if t.is_array:
            return "mlab::Mat"
        if t == BOOL:
            return "bool"
        return "f64"

    def declare(self, name, t, code, mutable, value=None):
        if t.kind == "func":
            return f"let {self.name(name)} = {code};"
        return f"let {'mut ' if mutable else ''}{self.name(name)}: {self.rtype(t)} = {code};"

    def default_value(self, t):
        return "mlab::Mat::default()" if t.is_array else "false" if t == BOOL else "0.0"

    def lambda_expr(self, e):
        saved = dict(self.env)
        for p in e.params:
            self.env[p] = SCALAR
        try:
            body = self.num(e.body, P_OR)
        finally:
            self.env = saved
        return f"move |{', '.join(self.name(p) + ': f64' for p in e.params)}| -> f64 {{ {body} }}"

    def call_lambda(self, e):
        return f"{self.name(e.base.name)}({', '.join(self.num(a, P_OR) for a in e.args)})"

    def call_local(self, name, args, node, full=False):
        f = self.local[name]
        ft = self._sig.get(name)
        if len(args) != len(f.params):
            self.unsupported(f"'{name}' muss mit genau {len(f.params)} Argumenten aufgerufen werden", node)
        codes = [self.mat_arg(a) if t.is_array else self.num(a, P_OR)
                 for a, t in zip(args, ft.inputs if ft else [SCALAR] * len(args))]
        if f is self.entry and self.persistent_entry:
            codes.insert(0, self.STATE_ARG)
        call = f"{self.name(name)}({', '.join(codes)})"
        if len(f.outputs) > 1 and not full:
            return f"{call}.0", P_POST
        return call, P_POST

    def if_head(self, cond, ind, first):
        return f"{ind}if {cond} {{" if first else f"{ind}}} else if {cond} {{"

    def else_head(self, ind):
        return f"{ind}}} else {{"

    def while_head(self, cond, ind):
        return f"{ind}while {cond} {{"

    def for_range_head(self, var, a, s, b, ind, name):
        mut = "mut " if self.counts.get(name, 0) > 2 else ""
        return f"{ind}for {mut}{var} in mlab::colon({a}, {s}, {b}) {{"

    def for_vec_head(self, var, vec, ind, name):
        return f"{ind}for {var} in {vec}.data.clone() {{"

    def return_stmt(self):
        outs = self.func.outputs
        if not outs:
            return "return;"
        vals = [self.name(o) + (".clone()" if self.env.get(o, SCALAR).is_array else "") for o in outs]
        if len(outs) == 1:
            return f"return {vals[0]};"
        return f"return ({', '.join(vals)});"

    def unpack(self, targets, fields, call, ind, n, pair=False):
        if n == 1 and not pair:
            return [f"{ind}{self.name(targets[0])} = {call};"] if targets[0] else [f"{ind}{call};"]
        names = [self.name(t) if t else "_" for t in targets] + ["_"] * (n - len(targets))
        return [f"{ind}({', '.join(names)}) = {call};"]

    def print_literal(self, text):
        return f"print!({self.string_literal(self.rust_format(text))});"

    def _args(self, vals):
        return "".join(", " + (self.string_literal(v) if k == "str" else v) for k, v in vals)

    def print_format(self, text, vals):
        return f"print!({self.string_literal(self.rust_format(text))}{self._args(vals)});"

    def raise_error(self, text, vals):
        return f"panic!({self.string_literal(self.rust_format(text))}{self._args(vals)});"

    def disp_mat(self, arg):
        return f"mlab::disp({arg});"

    # ------------------------------------------------------------------ file
    def generate(self):
        funcs = self.collect()
        self._sig = {f.name: ft for f, ft in funcs}
        self.persistent_entry = any(isinstance(s, N.Persistent) for s in N.body_statements(self.entry.body))
        module = self.entry.name
        out = [f"//! {l}".rstrip() for l in (self.entry.doc or module).split("\n")]
        eqs = []
        for f, _ in funcs:
            eqs += self.equations_of(f)
        out += ["//!", f"//! Generated by vdsim.matlab (target Rust) from {self.mfile.path or '<source>'}.",
                "//! Do not edit by hand; regenerate with: python -m vdsim.matlab convert <file.m> --to rust"]
        if eqs:
            out.append(f"//! Equation references: {', '.join(dict.fromkeys(eqs))}")
        out += ["#![allow(non_snake_case, unused_mut, unused_assignments, unused_variables, unused_parens, dead_code,",
                "         clippy::all)]", ""]
        if self.persistent_entry:
            pvars = sorted({n for s in N.body_statements(self.entry.body) if isinstance(s, N.Persistent)
                            for n in s.names})
            env0 = self._sig[module].env
            out += [f"/// Persistent variables of `{module}` (None until the first assignment, like MATLAB [])",
                    "#[derive(Debug, Clone, Default)]", f"pub struct {self.state_struct_name()} {{"]
            out += [f"    pub {n}: Option<{self.rtype(env0.get(n, SCALAR) if env0.get(n, SCALAR).kind != 'none' else SCALAR)}>,"
                    for n in pvars]
            out += ["}", ""]
        for f, ft in funcs:
            self.setup_function(f, ft)
            params = []
            prologue = []
            for p, t in zip(f.params, ft.inputs):
                if p == "~":
                    params.append("_: f64")
                elif t.is_array:
                    params.append(f"{self.name(p)}: &mlab::Mat")
                    if p in self.mutated or self.counts.get(p, 0):
                        prologue.append(f"    let mut {self.name(p)} = {self.name(p)}.clone();   // copy semantics")
                else:
                    mut = "mut " if self.counts.get(p, 0) else ""
                    params.append(f"{mut}{self.name(p)}: {self.rtype(t)}")
            if f is self.entry and self.persistent_entry:
                params.insert(0, f"{self.STATE_ARG}: &mut {self.state_struct_name()}")
            outs = [self.rtype(t if t.kind not in ("unknown", "none") else SCALAR) for t in ft.outputs]
            ret = "" if not outs else f" -> {outs[0]}" if len(outs) == 1 else f" -> ({', '.join(outs)})"
            vis = "pub " if f is self.entry else ""
            out += [f"/// {l}".rstrip() for l in f.doc.split("\n")] if f.doc else []
            out.append(f"{vis}fn {self.name(f.name)}({', '.join(params)}){ret} {{")
            out += prologue
            for n in self.hoisted:
                try:
                    t = self.vtype(n, f)
                    out.append(f"    let mut {self.name(n)}: {self.rtype(t)} = {self.default_value(t)};")
                except Unsupported as u:
                    self.diag("error", u.message, u.node or f)
            body = self.block(f.body, self.INDENT)
            out += body
            if f.outputs and (not body or not body[-1].strip().startswith("return")):
                out.append(f"    {self.return_stmt()}")
            out += ["}", ""]
        out.append(RUNTIME_RS)
        ft = self._sig[module]
        sig = {"module": module, "function": self.name(module),
               "inputs": [(p, str(t)) for p, t in zip(self.entry.params, ft.inputs)],
               "outputs": [(o, str(t)) for o, t in zip(self.entry.outputs, ft.outputs)],
               "state": self.state_struct_name() if self.persistent_entry else None}
        return GeneratedCode("rust", {f"{module}.rs": "\n".join(out)}, self.diags, self.name(module), sig)


